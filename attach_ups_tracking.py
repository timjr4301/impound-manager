def main():
    apply = '--apply' in sys.argv
    with app.app_context():
        pairs = (
            db.session.query(CertifiedLetter, Vehicle)
            .join(Vehicle, Vehicle.id == CertifiedLetter.vehicle_id)
            .filter(CertifiedLetter.letter_number == 1)
            .filter(CertifiedLetter.sent_date.isnot(None))
            .filter(db.or_(CertifiedLetter.tracking_number.is_(None),
                           CertifiedLetter.tracking_number == ''))
            .filter(CertifiedLetter.superseded.isnot(True))
            .filter(Vehicle.status == 'ACTIVE')
            .filter(Vehicle.possible_release.isnot(True))
            .order_by(CertifiedLetter.vehicle_id)
            .all()
        )

        matched, no_track = [], 0
        for letter, v in pairs:
            trk = TRACKING.get((v.invoice_number or '').strip())
            if not trk:
                no_track += 1
                continue
            matched.append((v, letter, trk))

        print(f'{"APPLYING" if apply else "DRY-RUN (no changes)"}')
        print(f'  sent 1st letters missing a tracking number: {len(pairs)}')
        print(f'  will attach a UPS tracking number:          {len(matched)}')
        print(f'  no UPS tracking match (left as-is):         {no_track}')
        print()

        for v, letter, trk in matched[:80]:
            desc = (v.display_name or "")[:28]
            print(f'  #{v.id:<6} inv {str(v.invoice_number or "-"):<10} {desc:<28} -> {trk}')
        if len(matched) > 80:
            print(f'  ... and {len(matched) - 80} more')

        if apply and matched:
            now = datetime.utcnow()
            for v, letter, trk in matched:
                letter.tracking_number = trk
                letter.updated_at = now
                db.session.add(VehicleNote(
                    vehicle_id=v.id,
                    body=('Attached UPS tracking ' + trk + ' to the 1st Notice Letter '
                          '(invoice ' + str(v.invoice_number) + ') so delivery auto-updates '
                          'and the 2nd-letter timer can start. Reconciliation of the July '
                          'outage; no 2nd letter or delivery date touched here.'),
                    author='System (UPS tracking attach)',
                    created_at=now,
                ))
            db.session.commit()
            print()
            print(f'Committed - {len(matched)} tracking numbers attached.')
            print('Next: hit "Refresh UPS Tracking" on the Letters page (or wait for the')
            print('auto-poll) to pull delivery and start the 2nd-letter timers.')
        elif not apply:
            print()
            print('Re-run with --apply to write these changes.')


if __name__ == '__main__':
    main()
